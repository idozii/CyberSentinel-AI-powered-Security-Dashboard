from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from pathlib import Path
from statistics import mean
from typing import Dict, List


def load_rows(path: Path) -> List[Dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        return list(reader)


def summarize(rows: List[Dict[str, str]]) -> Dict[str, object]:
    statuses = Counter(row.get("status_code", "") for row in rows)
    methods = Counter(row.get("http_method", "") for row in rows)
    services = Counter(row.get("service", "") for row in rows)
    durations = [float(row["duration_ms"]) for row in rows if row.get("duration_ms")]

    return {
        "rows": len(rows),
        "services": services.most_common(5),
        "methods": methods.most_common(5),
        "statuses": statuses.most_common(10),
        "avg_duration_ms": round(mean(durations), 3) if durations else 0.0,
    }


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Profile a training dataset before building an ML model.")
    parser.add_argument("--input", required=True, help="CSV file generated by scripts/etl.py.")
    return parser


def main() -> int:
    args = build_parser().parse_args()
    rows = load_rows(Path(args.input))
    print(json.dumps(summarize(rows), indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
